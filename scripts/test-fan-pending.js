'use strict';
const assert = require('assert'), fs = require('fs'), path = require('path'), vm = require('vm');
const source = fs.readFileSync(path.join(__dirname, '../overlay/var/www/ng/controllers.js'), 'utf8');
const start = source.indexOf('  var bsIntOr =');
const end = source.indexOf('  $scope.bsHeaderHashrate =', start);
let now = 100000;
const scope = {settings:{userAutoFan:true, userAutoFanMin:40}, status:{fanControl:{fan:70, status:'queued', pending:true}}};
const ctx = {$scope:scope, Date:{now:()=>now}};
vm.runInNewContext(source.slice(start, end), ctx);
scope.bsReceiveFanStatus({wait_seconds:60, pending:true, request_revision:'old'});
assert(!scope.bsAutoFanPending(), 'refresh and automatic adjustments do not start a countdown');
vm.runInNewContext("bsFanSavedRequest = {revision:'saved', deadline:Date.now()+60000};", ctx);
scope.bsReceiveFanStatus({wait_seconds:60, pending:true, request_revision:'saved'});
assert(scope.bsAutoFanPending());
assert.equal(scope.bsAutoFanLabel(), 'Updating Fan');
assert.equal(scope.bsAutoFanCountdown(), 60);
assert(!scope.bsAutoFanShowMin());
now += 12000;
assert.equal(scope.bsAutoFanCountdown(), 48);
scope.bsReceiveFanStatus({wait_seconds:48, pending:true, request_revision:'saved'});
assert.equal(scope.bsAutoFanCountdown(), 48, 'status polling does not restart the timer');
now += 60000;
assert.equal(scope.bsAutoFanCountdown(), 0);
assert.equal(scope.bsAutoFanLabel(), 'Updating Fan', 'no false completion at zero');
scope.status.fanControl = {fan:80, status:'ok', pending:false, request_revision:'saved'};
scope.bsReceiveFanStatus(scope.status.fanControl);
assert(!scope.bsAutoFanPending());
assert.equal(scope.bsAutoFanLabel(), 'Auto Fan');
assert.equal(scope.bsAutoFanActual(), 80);
assert(scope.bsAutoFanShowMin());
scope.status.fanControl = {fan:70, min_fan:20, status:'starting', pending:false};
assert.equal(scope.bsAutoFanLabel(), 'Updating Fan', 'startup recovery is not labeled as a fan fault');
assert.equal(scope.bsAutoFanActual(), 70, 'startup recovery preserves the reported fan speed');
assert(!scope.bsAutoFanPending(), 'automatic recovery does not start a save countdown');
assert.equal(scope.bsAutoFanState(), 'ramping');
scope.status.fanControl.status = 'error';
assert.equal(scope.bsAutoFanLabel(), 'Fan Error', 'real or persistent errors remain visible');
scope.status.fanControl.status = 'emergency';
assert.equal(scope.bsAutoFanLabel(), 'Emergency Fan', 'emergency indication is preserved');
scope.status.fanControl.status = 'ok';
assert.equal(scope.bsAutoFanLabel(), 'Auto Fan');
assert.equal(scope.bsAutoFanActual(), 70);
assert(scope.bsAutoFanShowMin());
vm.runInNewContext("bsFanSavedRequest = {revision:'new', deadline:Date.now()+60000};", ctx);
assert(scope.bsAutoFanPending(), 'save is pending before next status poll');
scope.bsReceiveFanStatus({request_revision:'old', wait_seconds:0});
assert(scope.bsAutoFanPending(), 'stale in-flight status cannot cancel the save');
scope.bsReceiveFanStatus({request_revision:'new', wait_seconds:0});
assert(scope.bsAutoFanPending(), 'missing acknowledgement cannot cancel the save');
scope.bsReceiveFanStatus({request_revision:'new', wait_seconds:0, pending:false});
assert(!scope.bsAutoFanPending());
console.log('PASS fan countdown, pending after zero, status confirmation and save/status race');
